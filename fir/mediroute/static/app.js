async function renderPage() {
  const content = $('#content');
  content.innerHTML = `<article class="card">${escapeHtml(t('loading', 'Loading secure data...'))}</article>`;
  setStatus('');
  try {
    if (state.page === 'Terms & Conditions') {
      content.innerHTML = renderTermsAndConditions(state.user.role);
      await bindPageEvents();
      return;
    }
    const role = state.user.role;
    const isDoctor = role === 'DOCTOR' || state.user.email === 'doctor@mediroute.demo';
    content.innerHTML = isDoctor ? await renderDoctor(state.page)
      : role === 'PATIENT' ? await renderPatient(state.page)
      : role === 'HOSPITAL' ? await renderHospital(state.page)
      : role === 'AMBULANCE_DRIVER' ? await renderDriver(state.page)
      : role === 'ADMIN' ? await renderAdmin(state.page)
      : await renderGovernment(state.page);
    await bindPageEvents();
  } catch (error) {
    content.innerHTML = `<article class="card"><p class="error">${escapeHtml(error.message)}</p></article>`;
  }
}

