function t(key, fallback = '') {
  if (state.i18n && state.i18n[key]) return state.i18n[key];
  const activeLangDict = i18nData[state.lang] || i18nData.en;
  if (activeLangDict && activeLangDict[key]) return activeLangDict[key];
  if (i18nData.en && i18nData.en[key]) return i18nData.en[key];
  return fallback || key;
}

