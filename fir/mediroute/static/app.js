async function api(path, options = {}) {
  const headers = {
    ...(options.body ? { 'Content-Type': 'application/json' } : {}),
    ...(state.token ? { Authorization: `Bearer ${state.token}` } : {}),
    ...(options.headers || {})
  };
  const retryable = !options.method || options.method === 'GET';
  let lastError;
  for (let attempt = 0; attempt < (retryable ? 3 : 1); attempt += 1) {
    try {
      const response = await fetch(`/api${path}`, { ...options, headers });
      const data = response.status === 204 ? null : await response.json();
      if (!response.ok) throw new Error(typeof data.detail === 'string' ? data.detail : (data.message || 'Request failed'));
      return data;
    } catch (error) {
      lastError = error;
      if (attempt < 2) await new Promise(resolve => setTimeout(resolve, 300 * (attempt + 1)));
    }
  }
  throw new Error(`Connection problem: ${lastError.message}.`);
}

