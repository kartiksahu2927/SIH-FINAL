function setupVoiceRecognition() {
  const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
  if (!SpeechRecognition) {
    setStatus(t('mic_unsupported', 'Speech recognition not supported in this browser. Please type your message.'));
    return null;
  }
  const recognizer = new SpeechRecognition();
  recognizer.continuous = false;
  recognizer.interimResults = false;
  const langMap = { en: 'en-IN', hi: 'hi-IN', bn: 'bn-IN', mr: 'mr-IN', ta: 'ta-IN', te: 'te-IN' };
  recognizer.lang = langMap[state.lang] || 'en-IN';

  recognizer.onstart = () => {
    state.recognitionRunning = true;
    const btn = $('#mic-btn');
    if (btn) btn.classList.add('recording');
    setStatus(t('listening', 'Listening...'));
  };

  recognizer.onresult = (event) => {
    const transcript = event.results[0][0].transcript;
    const input = $('#emergency-message-input');
    if (input) {
      input.value = transcript;
      sendEmergencyAssistantMessage(transcript);
    }
  };

  recognizer.onerror = (event) => {
    console.warn('Speech recognition error:', event.error);
    state.recognitionRunning = false;
    const btn = $('#mic-btn');
    if (btn) btn.classList.remove('recording');
  };

  recognizer.onend = () => {
    state.recognitionRunning = false;
    const btn = $('#mic-btn');
    if (btn) btn.classList.remove('recording');
  };

  return recognizer;
}

function toggleReadAloud(btn) {
  if (!('speechSynthesis' in window)) {
    setStatus('Text-to-speech not supported on this browser.');
    return;
  }
  if (window.speechSynthesis.speaking) {
    window.speechSynthesis.cancel();
    document.querySelectorAll('.speak-btn').forEach(b => { b.textContent = '🔊 Listen'; b.dataset.speaking = 'false'; });
    if (btn.dataset.speaking === 'true') {
      btn.dataset.speaking = 'false';
      return;
    }
  }
  const bubble = btn.closest('.chat-bubble');
  if (!bubble) return;
  const clone = bubble.cloneNode(true);
  clone.querySelectorAll('button, .chat-bubble-source, .speak-btn').forEach(el => el.remove());
  const textToRead = clone.innerText.trim();
  if (!textToRead) return;

  const utterance = new SpeechSynthesisUtterance(textToRead);
  const langMap = { en: 'en-IN', hi: 'hi-IN', bn: 'bn-IN', mr: 'mr-IN', ta: 'ta-IN', te: 'te-IN' };
  utterance.lang = langMap[state.lang] || 'en-IN';
  utterance.rate = 0.92;

  btn.textContent = '⏹ Stop';
  btn.dataset.speaking = 'true';

  utterance.onend = () => {
    btn.textContent = '🔊 Listen';
    btn.dataset.speaking = 'false';
  };
  utterance.onerror = () => {
    btn.textContent = '🔊 Listen';
    btn.dataset.speaking = 'false';
  };

  window.speechSynthesis.speak(utterance);
}
window.toggleReadAloud = toggleReadAloud;

